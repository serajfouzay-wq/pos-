#!/usr/bin/env node
/**
 * Turns `clients/<slug>/` (committed by the generator) into the inputs of a
 * client-specific POS build:
 *
 * - `apps/pos-client/src-tauri/tauri.client.json`: Tauri config overrides
 *   (product name, per-client app identifier, window title, bundled receipt
 *   logo, client icons), passed to `tauri build --config`;
 * - `apps/pos-client/src-tauri/client-assets/receipt-logo.png` when the
 *   client has a logo (bundled as a resource; the till reads it at start-up);
 * - environment for the Rust build: `POS_CLIENT_CONFIG` (validated again by
 *   build.rs with the same rules the till uses) and `POS_LICENSE_PUBLIC_KEY`.
 *
 * Usage: node scripts/prepare-client-build.mjs <slug>
 * In GitHub Actions the environment goes to $GITHUB_ENV and `has_icon` to
 * $GITHUB_OUTPUT; elsewhere it is printed.
 */
import {
  appendFileSync,
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const ICON_FILES = ['32x32.png', '128x128.png', '128x128@2x.png', 'icon.icns', 'icon.ico'];

/** Installer/product names end up in file names: keep them plain ASCII. */
export function productName(displayName, slug) {
  const ascii = displayName
    .normalize('NFKD')
    .replace(/[^A-Za-z0-9 .\-]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 60);
  return ascii.length >= 2 ? ascii : `POS ${slug}`;
}

export function prepare({ root, slug }) {
  if (!SLUG.test(slug) || slug.length > 40) {
    throw new Error(`invalid client slug: ${slug}`);
  }
  const clientDir = join(root, 'clients', slug);
  const configPath = join(clientDir, 'client.json');
  const keyPath = join(clientDir, 'license-public-key.pem');
  if (!existsSync(configPath)) throw new Error(`missing ${configPath}`);
  if (!existsSync(keyPath)) throw new Error(`missing ${keyPath}`);

  const config = JSON.parse(readFileSync(configPath, 'utf8'));
  if (config.client_slug !== slug) {
    throw new Error(`client.json is for "${config.client_slug}", not "${slug}"`);
  }
  if (!readFileSync(keyPath, 'utf8').includes('-----BEGIN PUBLIC KEY-----')) {
    throw new Error('license-public-key.pem is not a public key');
  }

  const tauriDir = join(root, 'apps', 'pos-client', 'src-tauri');
  const base = JSON.parse(readFileSync(join(tauriDir, 'tauri.conf.json'), 'utf8'));
  const name = productName(config.display_name, slug);

  // JSON merge patch semantics: arrays are replaced, so windows is complete.
  const overrides = {
    productName: name,
    identifier: `com.posfactory.pos.${slug}`,
    app: {
      windows: base.app.windows.map((w, i) => (i === 0 ? { ...w, title: config.display_name } : w)),
    },
    bundle: {
      shortDescription: `${config.display_name} point of sale`,
      resources: {},
    },
  };

  const logo = config.receipt?.logo_asset ?? null;
  if (logo !== null) {
    if (logo !== 'receipt-logo.png') throw new Error(`unexpected logo asset ${logo}`);
    const source = join(clientDir, logo);
    if (!existsSync(source)) throw new Error(`client.json references ${logo}, which is missing`);
    mkdirSync(join(tauriDir, 'client-assets'), { recursive: true });
    copyFileSync(source, join(tauriDir, 'client-assets', logo));
    overrides.bundle.resources[`client-assets/${logo}`] = `client-assets/${logo}`;
  }

  const hasIcon = existsSync(join(clientDir, 'app-icon.png'));
  if (hasIcon) {
    // Generated by `tauri icon … -o client-icons` in the next workflow step.
    overrides.bundle.icon = ICON_FILES.map((file) => `client-icons/${file}`);
  }

  const overridesPath = join(tauriDir, 'tauri.client.json');
  writeFileSync(overridesPath, `${JSON.stringify(overrides, null, 2)}\n`);
  return {
    overrides,
    overridesPath,
    hasIcon,
    env: { POS_CLIENT_CONFIG: resolve(configPath), POS_LICENSE_PUBLIC_KEY: resolve(keyPath) },
  };
}

function main() {
  const slug = process.argv[2] ?? '';
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const result = prepare({ root, slug });
  const envLines = Object.entries(result.env).map(([k, v]) => `${k}=${v}`);
  if (process.env.GITHUB_ENV) appendFileSync(process.env.GITHUB_ENV, `${envLines.join('\n')}\n`);
  else console.log(envLines.join('\n'));
  if (process.env.GITHUB_OUTPUT) {
    appendFileSync(process.env.GITHUB_OUTPUT, `has_icon=${String(result.hasIcon)}\n`);
  }
  console.log(`prepared ${result.overrides.productName} (${result.overrides.identifier})`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(`::error::${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
